#pragma once

#include <algorithm>

namespace find_offer {

class Solution {
public:
    // 672. 灯泡开关 Ⅱ
    // 分析与降维思想：
    // 1. 按钮互斥与周期性：
    //    由于所有按钮都是“翻转”操作，按两次等于没按（异或逻辑）。操作次数的奇偶性决定了最终状态。
    //    并且，同时按按钮1和2等效于按按钮3。总共只有 8 种本质不同的状态。
    // 2. 灯泡状态循环节：
    //    按钮 1：周期 1
    //    按钮 2、3：周期 2
    //    按钮 4 (3k+1)：周期 3
    //    根据最小公倍数，所有灯泡的状态以 6 为周期完全重复。
    //    而且进一步推理，当 n >= 3 时，前三个灯泡的状态足以区分所有 8 种组合结果（因为没有两种不同的底层组合会让前 3 个灯泡完全呈现一模一样的死角）。
    //    因此，如果 n > 3，我们可以直接把 n 视作 3。
    //
    // 3. 构建硬编码结果地图 (n 转化为 min(n, 3))：
    //    - presses == 0：不用按，保持原样 -> 1 种
    //    - n == 1: 无论按什么，1号灯只能是亮或灭 -> 2 种
    //    - n == 2:
    //         - presses == 1: 会出现 3 种情况。
    //         - presses >= 2: 会出现满编 4 种情况。
    //    - n >= 3:
    //         - presses == 1: 按1/2/3/4其中之一，衍生出 4 种情况。
    //         - presses == 2: 任组合2个不同按钮（或同按1个抵消为0），可以组合出 7 种情况。
    //         - presses >= 3: 足以遍历组合出全部的 8 种可能性。
    int flipLights(int n, int presses) {
        // 不需要操作，永远只有一种初始状态（全亮）
        if (presses == 0) return 1;

        // 根据前面的推理，灯泡数量的有效阈值只有 1，2，3（以及超过 3）。
        n = std::min(n, 3);
        
        if (n == 1) {
            // 只有1个灯泡的情况最简单，只有亮或灭
            return 2;
        } else if (n == 2) {
            // 2个灯泡，单按操作有3种状态组合，超过1次操作则有满集的4种组合
            return presses == 1 ? 3 : 4;
        } else {
            // >= 3个灯泡，开始逼近 8 种满状态
            if (presses == 1) {
                return 4;  // 单按1, 2, 3, 4 分别出4种不同状态
            } else if (presses == 2) {
                return 7;  // 两次操作可以构造出 7 个分身状态
            } else {
                return 8;  // 按3次以上可以构造全部的 8 种完全状态集
            }
        }
    }
};

} // namespace find_offer
